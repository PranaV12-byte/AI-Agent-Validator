import { mkdirSync } from "node:fs"
import { resolve } from "node:path"
import { expect, test } from "@playwright/test"

test("dev foundation preview stays truthful, accessible, and responsive", async ({ page }) => {
  const evidenceDirectory = resolve("test-results/foundation")
  mkdirSync(evidenceDirectory, { recursive: true })

  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto("/__ui/foundation")
  await page.evaluate(() => document.fonts.ready.then(() => true))
  await expect(page.getByRole("heading", { name: "Test a prompt" })).toBeVisible()
  await expect(page.getByText("Development-only component preview")).toBeVisible()
  await expect(page.getByRole("button", { name: "Open preview navigation" })).toBeHidden()
  await expect(page.getByRole("navigation", { name: "Preview navigation" }).getByRole("link", { name: "Test", exact: true })).toHaveAttribute("aria-current", "page")
  await expect(page.getByRole("button", { name: "Run check" }).first()).toBeDisabled()
  await expect(page.getByText("No check has run. This preview does not send prompts or produce safety results.")).toBeVisible()
  await expect(page.getByRole("link", { name: "Help & feedback" })).toBeInViewport()
  await page.screenshot({ path: resolve(evidenceDirectory, "desktop-expanded.png"), fullPage: true, animations: "disabled" })

  const main = page.locator(".fd-main")
  const expandedWidth = await main.evaluate((element) => element.getBoundingClientRect().width)
  const collapseButton = page.getByRole("button", { name: "Collapse sidebar" })
  await expect(collapseButton).toHaveAttribute("aria-expanded", "true")
  await expect(collapseButton).toHaveAttribute("aria-controls", "preview-sidebar-menu")
  await collapseButton.click()
  const expandButton = page.getByRole("button", { name: "Expand sidebar" })
  await expect(expandButton).toHaveAttribute("aria-expanded", "false")
  await expect(expandButton).toBeFocused()
  await expect(page.locator(".fd-sidebar")).toHaveClass(/fd-sidebar--collapsed/)
  const compactWidth = await main.evaluate((element) => element.getBoundingClientRect().width)
  expect(compactWidth).toBeGreaterThan(expandedWidth + 100)
  await page.screenshot({ path: resolve(evidenceDirectory, "desktop-collapsed.png"), fullPage: true, animations: "disabled" })
  const protectionLink = page.getByRole("link", { name: "Protection" })
  await expect(protectionLink).toHaveAttribute("aria-label", "Protection")
  await expect(protectionLink).toHaveAttribute("title", "Protection")
  await expect(page.getByRole("link", { name: "Activity" })).toHaveAttribute("aria-disabled", "true")
  await expect(page.getByRole("link", { name: "Connect" })).toHaveAttribute("aria-disabled", "true")
  await protectionLink.hover()
  const protectionTooltip = page.getByRole("tooltip")
  await expect(protectionTooltip).toHaveText("Protection")
  await protectionTooltip.hover()
  await expect(protectionTooltip).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(protectionTooltip).toHaveCount(0)
  await protectionLink.focus()
  await expect(protectionTooltip).toHaveText("Protection")
  await expect(protectionLink).toHaveAttribute("aria-describedby", /.+/)
  await expect(page.getByRole("link", { name: "Account settings" })).toBeInViewport()
  await expect(page.getByRole("link", { name: "Help & feedback" })).toBeInViewport()
  await page.locator(".fd-sidebar").screenshot({ path: resolve(evidenceDirectory, "sidebar-collapsed.png"), animations: "disabled" })
  await page.setViewportSize({ width: 1440, height: 400 })
  await expect(expandButton).toBeInViewport()
  await expect(page.getByRole("link", { name: "Account settings" })).toBeInViewport()
  await expect(page.getByRole("link", { name: "Help & feedback" })).toBeInViewport()
  await page.setViewportSize({ width: 1440, height: 900 })
  await expandButton.click()
  await expect(page.getByRole("button", { name: "Collapse sidebar" })).toHaveAttribute("aria-expanded", "true")
  await expect(page.locator(".fd-sidebar")).not.toHaveClass(/fd-sidebar--collapsed/)

  await page.locator(".fd-test-card").screenshot({ path: resolve(evidenceDirectory, "test-card-desktop.png"), animations: "disabled" })
  await page.locator(".fd-logo-samples").scrollIntoViewIfNeeded()
  await page.locator(".fd-logo-samples").screenshot({ path: resolve(evidenceDirectory, "frame-sizes.png"), animations: "disabled" })
  for (const size of [24, 32, 64]) {
    const sample = page.getByTestId("logo-size-" + size)
    await expect(sample.locator("svg")).toHaveAttribute("width", String(size))
    await expect(sample.locator("svg")).toHaveAttribute("data-internal-gap", "2")
  }

  await page.locator("#protection-preview").scrollIntoViewIfNeeded()
  const modalTrigger = page.getByRole("button", { name: "Open rule modal preview" })
  await modalTrigger.click()
  let dialog = page.getByRole("dialog", { name: "Add protection rule" })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByRole("button", { name: "Close dialog" })).toBeFocused()
  await expect(page.locator(".fd-shell")).toHaveAttribute("inert", "")
  await expect(page.locator(".fd-shell")).toHaveAttribute("aria-hidden", "true")
  await expect(page.locator("body")).toHaveCSS("overflow", "hidden")
  await page.screenshot({ path: resolve(evidenceDirectory, "rule-modal-desktop.png"), animations: "disabled" })
  await page.keyboard.press("Shift+Tab")
  await expect(dialog.getByRole("button", { name: "Cancel" })).toBeFocused()
  await page.keyboard.press("Tab")
  await expect(dialog.getByRole("button", { name: "Close dialog" })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(dialog).toBeHidden()
  await expect(modalTrigger).toBeFocused()
  await expect(page.locator(".fd-shell")).not.toHaveAttribute("inert")
  await expect(page.locator("body")).not.toHaveCSS("overflow", "hidden")

  await page.locator("#account-preview").scrollIntoViewIfNeeded()
  const accountCard = page.getByRole("heading", { name: "Account tabs" }).locator("xpath=ancestor::section[1]")
  await accountCard.screenshot({ path: resolve(evidenceDirectory, "profile-tab.png"), animations: "disabled" })
  await page.getByRole("tab", { name: "Security" }).click()
  await expect(page.getByRole("tabpanel").getByLabel("New password")).toHaveValue("")
  await accountCard.screenshot({ path: resolve(evidenceDirectory, "security-tab.png"), animations: "disabled" })
  await page.getByRole("tab", { name: "Profile" }).click()
  await page.getByLabel("Workspace name").fill("Synthetic Draft Studio")
  await page.getByRole("tab").filter({ hasText: "Security" }).focus()
  await page.keyboard.press("ArrowRight")
  await expect(page.getByRole("tab", { name: "Profile" })).toHaveAttribute("aria-selected", "true")
  await expect(page.getByLabel("Workspace name")).toHaveValue("Synthetic Draft Studio")

  await page.getByRole("button", { name: "Collapse sidebar" }).click()
  await page.setViewportSize({ width: 390, height: 480 })
  await expect(page.locator(".fd-brand__wordmark")).toBeVisible()
  await page.getByRole("button", { name: "Open rule modal preview" }).click()
  dialog = page.getByRole("dialog", { name: "Add protection rule" })
  const longSample = Array.from({ length: 16 }, (_, index) => "Synthetic example paragraph " + (index + 1) + ".").join("\n")
  await dialog.getByRole("textbox", { name: "Example description" }).fill(longSample)
  const modalScrolls = await dialog.evaluate((element) => element.scrollHeight > element.clientHeight)
  expect(modalScrolls).toBe(true)
  await dialog.evaluate((element) => { element.scrollTop = element.scrollHeight })
  await expect(dialog).toBeInViewport()
  await page.screenshot({ path: resolve(evidenceDirectory, "rule-modal-mobile-scroll.png") })
  await page.keyboard.press("Escape")
  await expect(page.getByRole("button", { name: "Open rule modal preview" })).toBeFocused()

  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  const mobileToggle = page.getByRole("button", { name: "Open preview navigation" })
  await expect(page.getByRole("button", { name: "Collapse sidebar" })).toBeHidden()
  await expect(mobileToggle).toHaveAttribute("aria-expanded", "false")
  await expect(mobileToggle).toHaveAttribute("aria-controls", "preview-sidebar-menu")
  await expect(page.locator(".fd-sidebar__menu")).toBeHidden()
  await expect(page.locator(".fd-brand__wordmark")).toBeVisible()
  await page.screenshot({ path: resolve(evidenceDirectory, "mobile-navigation-closed.png"), fullPage: true, animations: "disabled" })
  await mobileToggle.click()
  const mobileCloseToggle = page.getByRole("button", { name: "Close preview navigation" })
  await expect(mobileCloseToggle).toHaveAttribute("aria-expanded", "true")
  await page.screenshot({ path: resolve(evidenceDirectory, "mobile-navigation-open.png"), fullPage: true, animations: "disabled" })
  await page.keyboard.press("Escape")
  await expect(mobileToggle).toBeFocused()
  await expect(page.locator(".fd-sidebar__menu")).toBeHidden()
  await mobileToggle.click()
  await expect(page.locator(".fd-sidebar__menu")).toBeVisible()
  await mobileCloseToggle.focus()
  await page.keyboard.press("Tab")
  await expect(page.getByRole("link", { name: "Test" })).toBeFocused()
  await page.keyboard.press("Escape")
  await expect(mobileToggle).toBeFocused()
  await expect(page.locator(".fd-sidebar__menu")).toBeHidden()
  await page.keyboard.press("Tab")
  const focusStayedOutsideClosedMenu = await page.evaluate(() => !document.activeElement?.closest(".fd-sidebar__menu"))
  expect(focusStayedOutsideClosedMenu).toBe(true)
  await mobileToggle.click()
  await page.getByRole("link", { name: "Protection" }).click()
  await expect(page).toHaveURL(/#protection-preview$/)
  await expect(page.locator("#protection-preview")).toBeFocused()
  await expect(page.locator(".fd-sidebar__menu")).toBeHidden()
  await mobileToggle.click()
  await page.getByRole("link", { name: "SafeBot preview home" }).click()
  await expect(page).toHaveURL(/#test-preview$/)
  await expect(page.locator("#test-preview")).toBeFocused()
  await expect(page.locator(".fd-sidebar__menu")).toBeHidden()

  await page.setViewportSize({ width: 1440, height: 900 })
  await expect(page.getByRole("button", { name: "Expand sidebar" })).toBeVisible()
  await expect(page.getByRole("button", { name: "Open preview navigation" })).toBeHidden()
  await expect(page.getByRole("button", { name: "Expand sidebar" })).toHaveAttribute("aria-expanded", "false")
  await expect(page.locator(".fd-sidebar")).toHaveClass(/fd-sidebar--collapsed/)
  await expect(page.locator(".fd-brand__wordmark")).toBeHidden()
  await expect(page.locator(".fd-sidebar__menu")).toBeVisible()
  await page.getByRole("button", { name: "Expand sidebar" }).click()
  await expect(page.locator(".fd-sidebar")).not.toHaveClass(/fd-sidebar--collapsed/)

  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await expect(page.getByRole("heading", { name: "Test a prompt" })).toBeVisible()
  await page.screenshot({ path: resolve(evidenceDirectory, "test-mobile-390.png"), animations: "disabled" })
  await page.setViewportSize({ width: 320, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  const pageWidths = await page.evaluate(() => ({
    document: document.documentElement.scrollWidth,
    viewport: window.innerWidth,
  }))
  expect(pageWidths.document).toBeLessThanOrEqual(pageWidths.viewport)
  await page.screenshot({ path: resolve(evidenceDirectory, "test-mobile-320.png"), animations: "disabled" })

  await page.goto("/dashboard")
  await expect(page).toHaveURL(/\/login(?:\?|$)/)
})
